// Builds src/model/idd-fields.js, the field map the IDF reader and writer use (src/model/idf.js), from
// EnergyPlus's own schema (Energy+.schema.epJSON, which carries the IDD's field order as legacy_idd).
//   node tools/build-idd.mjs [path to Energy+.schema.epJSON]
// For each object type: f, its fields in IDF order (name first where it has one); n, which of them are
// numbers; x and xn, the fields of its extensible group and which are numbers; e, the epJSON key the
// group is kept under; named, whether it has a name (the object's key in epJSON); c, each field's
// choices, for their spelling (IDF is not case sensitive, epJSON's choices are).
import { readFileSync, writeFileSync } from 'node:fs';

const src = process.argv[2] || 'C:/EnergyPlus-23.1.0/Energy+.schema.epJSON';
const schema = JSON.parse(readFileSync(src, 'utf8'));
const choicesOf = (p) => {
  if (!p) return null;
  const all = [...(p.enum || []), ...(p.anyOf || []).flatMap((a) => a.enum || [])].filter((v) => typeof v === 'string' && v !== '');
  return all.length ? all : null;
};
const out = { version: schema.epJSON_schema_version || null, types: {} };
for (const [type, o] of Object.entries(schema.properties)) {
  const L = o.legacy_idd, props = Object.values(o.patternProperties || {})[0]?.properties || {};
  if (!L) continue;
  const fields = L.fields || [], ext = L.extensibles || [];
  const t = { f: fields };
  const n = fields.map((f, i) => (L.field_info?.[f]?.field_type === 'n' ? i : -1)).filter((i) => i >= 0);
  if (n.length) t.n = n;
  if (ext.length) {
    t.x = ext; t.e = L.extension;
    const xn = ext.map((f, i) => (L.field_info?.[f]?.field_type === 'n' ? i : -1)).filter((i) => i >= 0);
    if (xn.length) t.xn = xn;
  }
  if (o.name) t.named = 1;
  const c = {};
  for (const f of fields) { const ch = choicesOf(props[f]); if (ch) c[f] = ch; }
  const items = props[L.extension]?.items?.properties || {};
  for (const f of ext) { const ch = choicesOf(items[f]); if (ch) c[f] = ch; }
  if (Object.keys(c).length) t.c = c;
  out.types[type] = t;
}
const text = `// Generated by tools/build-idd.mjs from EnergyPlus's Energy+.schema.epJSON (version ${out.version}). Do not edit.\nexport default ${JSON.stringify(out)};\n`;
writeFileSync(new URL('../src/model/idd-fields.js', import.meta.url), text);
console.log(Object.keys(out.types).length, 'types,', (text.length / 1024).toFixed(0), 'kB');
